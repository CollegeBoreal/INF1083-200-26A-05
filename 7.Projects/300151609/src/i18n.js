const DICTS = { fr, ar, en }

export function makeT(lang) {
  const dict = DICTS[lang] || fr
  return (key, vars) => {
    let s = dict[key] ?? fr[key] ?? key
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m))
    }
    return s
  }
}

export function localeOf(lang) {
  return (LANGS.find((l) => l.code === lang) || LANGS[0]).locale
}

export function dirOf(lang) {
  return lang === 'ar' ? 'rtl' : 'ltr'
}

export function foodName(food, lang) {
  if (!food) return ''
  return food.names[lang] || food.names.fr
}

export function normalize(str) {
  return String(str)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[\u064B-\u0652\u0670]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .toLowerCase()
    .trim()
}
